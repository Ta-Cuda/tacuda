"""Generate the per-family C# wrappers for the streaming API.

The main generator (generate_bindings.py) models array-in/array-out calls and
cannot express a handle with a lifetime, so the streaming surface gets its own
emitter. Only the repetitive part is generated: the handle plumbing, lifetime
and execution policy live in the hand-written bindings/csharp/Stream.cs.

    python bindings/generate_stream_bindings.py           # write
    python bindings/generate_stream_bindings.py --check    # verify up to date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import List, Sequence, Tuple

ROOT = Path(__file__).resolve().parents[1]
CSHARP_OUT = ROOT / "bindings" / "csharp" / "Stream.Families.cs"

# (class stem, C stem, input components, output line names, create parameters)
FAMILIES: Sequence[Tuple[str, str, List[str], List[str], List[Tuple[str, str]]]] = (
    ("Sma", "sma", ["close"], ["Value"], [("int", "period")]),
    ("Ema", "ema", ["close"], ["Value"], [("int", "period")]),
    ("Wma", "wma", ["close"], ["Value"], [("int", "period")]),
    ("Rsi", "rsi", ["close"], ["Value"], [("int", "period")]),
    ("Atr", "atr", ["high", "low", "close"], ["Value"], [("int", "period")]),
    ("Natr", "natr", ["high", "low", "close"], ["Value"], [("int", "period")]),
    ("Obv", "obv", ["close", "volume"], ["Value"], []),
    ("Ad", "ad", ["high", "low", "close", "volume"], ["Value"], []),
    ("Macd", "macd", ["close"], ["Macd", "Signal", "Hist"],
     [("int", "fastPeriod"), ("int", "slowPeriod"), ("int", "signalPeriod")]),
    ("Bbands", "bbands", ["close"], ["Upper", "Middle", "Lower"],
     [("int", "period"), ("float", "upperMul"), ("float", "lowerMul")]),
)

# Project signature stamped on every generated file (keep in sync with
# scripts/add_source_headers.py, which stamps the hand-written sources —
# without it, that script would stamp this output and the --check gate below
# would report the file as stale on every run).
_SIGN_LINES = (
    "TaCuda | GPU-accelerated technical analysis | https://tacuda.com",
    "Copyright (c) 2024-2026 Paul Deecalov <paul@deecalov.com>",
    "SPDX-License-Identifier: Apache-2.0",
)


def signature(prefix: str = "//") -> str:
    bar = prefix + " " + "=" * (77 - len(prefix))
    body = [f"{prefix}  {ln}" for ln in _SIGN_LINES]
    return "\n".join([bar, *body, bar]) + "\n"


HEADER = signature() + """// <auto-generated>
// Generated by bindings/generate_stream_bindings.py - do not edit manually.
// Idiomatic wrappers over the streaming C ABI; the plumbing lives in Stream.cs.
// </auto-generated>
using System;

namespace Tacuda.Bindings;
"""


def _return_type(outs: Sequence[str]) -> str:
    if len(outs) == 1:
        return "float[]"
    return "(" + ", ".join(f"float[] {o}" for o in outs) + ")"


def render() -> str:
    parts: List[str] = [HEADER]

    for cls, stem, inputs, outs, params in FAMILIES:
        ctor_args = ", ".join(f"{t} {n}" for t, n in params)
        ctor_pass = "".join(f"{n}, " for _, n in params)
        ctor_names = ", ".join(n for _, n in params)
        sep = ", " if params else ""
        in_args = ", ".join(f"float[] {i}" for i in inputs)
        in_pass = ", ".join(inputs)
        first = inputs[0]
        out_pass = ", ".join(f"out{k}" for k in range(len(outs)))
        ret = ("out0" if len(outs) == 1
               else "(" + ", ".join(f"out{k}" for k in range(len(outs))) + ")")
        single_alloc = "\n".join(f"        float[] out{k} = Allocate(n);"
                                 for k in range(len(outs)))
        batch_alloc = "\n".join(f"        float[] out{k} = Allocate(total);"
                                for k in range(len(outs)))
        len_check = (f'\n        RequireSameLength("{cls}Stream.Append", {in_pass});'
                     if len(inputs) > 1 else "")
        len_check_b = (f'\n        RequireSameLength("{cls}StreamBatch.Append", {in_pass});'
                       if len(inputs) > 1 else "")

        parts.append(f"""
/// <summary>Incremental {stem.upper()} over one series.</summary>
public sealed class {cls}Stream : TacudaStream
{{
    public {cls}Stream({ctor_args}) : base(Create({ctor_names}), false) {{ }}

    private static IntPtr Create({ctor_args})
    {{
        NativeMethods.ThrowOnError(
            NativeMethods.ct_{stem}_stream_create({ctor_pass}out IntPtr handle),
            "ct_{stem}_stream_create");
        return handle;
    }}

    /// <summary>Append bars; returns one value per appended bar.</summary>
    public {_return_type(outs)} Append({in_args})
    {{
        IntPtr handle = Require();{len_check}
        int n = {first}.Length;
        RequireBars(n);
{single_alloc}
        NativeMethods.ThrowOnError(
            NativeMethods.ct_{stem}_stream_append(handle, {in_pass}, n, {out_pass}),
            "ct_{stem}_stream_append");
        return {ret};
    }}
}}

/// <summary>Incremental {stem.upper()} over a portfolio of series (series-major matrices).</summary>
public sealed class {cls}StreamBatch : TacudaStreamBatch
{{
    public {cls}StreamBatch({ctor_args}{sep}int numSeries)
        : base(Create({ctor_pass}numSeries)) {{ }}

    private static IntPtr Create({ctor_args}{sep}int numSeries)
    {{
        NativeMethods.ThrowOnError(
            NativeMethods.ct_{stem}_stream_batch_create({ctor_pass}numSeries, out IntPtr handle),
            "ct_{stem}_stream_batch_create");
        return handle;
    }}

    /// <summary>Append bars to every series; matrices are series-major.</summary>
    public {_return_type(outs)} Append({in_args})
    {{
        IntPtr handle = Require();{len_check_b}
        int total = {first}.Length;
        int n = BarsPerSeries(total);
{batch_alloc}
        NativeMethods.ThrowOnError(
            NativeMethods.ct_{stem}_stream_batch_append(handle, {in_pass}, n, {out_pass}),
            "ct_{stem}_stream_batch_append");
        return {ret};
    }}
}}""")

    return "\n".join(parts) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail when the generated file is stale")
    args = ap.parse_args()

    content = render()
    rel = CSHARP_OUT.relative_to(ROOT)

    if args.check:
        try:
            current = CSHARP_OUT.read_text(encoding="utf-8")
        except FileNotFoundError:
            print(f"MISSING: {rel}")
            return 1
        if current != content:
            print(f"STALE: {rel} — rerun bindings/generate_stream_bindings.py")
            return 1
        print(f"up to date: {rel}")
        return 0

    CSHARP_OUT.write_text(content, encoding="utf-8")
    print(f"wrote {rel} ({len(FAMILIES)} families)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
